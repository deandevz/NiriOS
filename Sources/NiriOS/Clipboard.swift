import AppKit
import Carbon.HIToolbox
import CryptoKit
import NiriCore

/// Histórico do Option+V. As regras da lista ficam em `ClipboardList`; a janela, em `ClipboardPanel`.
///
/// O macOS não avisa quando algo é copiado. Em vez de consultar o clipboard a cada 0,5 s (o Maccy faz assim), lê o
/// contador dele (`changeCount`, 0,6 µs) depois de tecla com Cmd, Return (o `pbcopy` no terminal) e clique solto
/// (menu Copiar, botão de copiar, o copiar ao selecionar do WezTerm), e ao abrir o painel. Parado, não roda nada.
/// Limite: várias cópias seguidas sem tecla nem clique (um script) entram só a última.
///
/// Este processo nunca lê nem escreve o conteúdo do clipboard, só o contador. Ler um TIFF de 30 MB aqui deixava 60 MB
/// presos (o NSPasteboard e o malloc guardam os buffers; nem trocar o clipboard nem `malloc_zone_pressure_relief`
/// devolvem, medido). Cada cópia nova é lida por um processo curto (`niri-os --clipboard-read`), que grava os arquivos
/// e sai; colar, quem escreve é o processo do painel (`niri-os --clipboard`, ver `ClipboardPanel`), que sai em seguida.
/// O painel recebe a lista pelo stdin (uma linha de JSON ao abrir e a cada cópia nova) e manda os pedidos pelo stdout.
///
/// Em disco, em ~/Library/Application Support/niri-os/clipboard: a lista (`index.json`) e uma pasta por cópia, com um
/// arquivo por formato (`public.rtf`...) e a miniatura das imagens (`thumbnail.png`, feita pelo painel). Na memória, só
/// a lista.
final class Clipboard {
    /// Texto vai com a formatação, e imagem num formato só, o primeiro que o app deu (o PNG costuma vir junto do TIFF,
    /// com 1/3 do tamanho). O resto (webarchive, tipos próprios do app) é grande e só o app de origem entende.
    static let textTypes: [NSPasteboard.PasteboardType] = [.string, .rtf, .html]
    static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, .init("public.jpeg")]
    /// Gerenciador de senha marca a cópia assim (padrão do nspasteboard.org): não entra no histórico.
    private static let secret: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    /// Maior que isso não entra (o TIFF de um print da tela Retina tem ~30 MB).
    private static let maxBytes = 50 << 20
    /// `NIRI_CLIPBOARD=<pasta>` usa outra (pra testar sem mexer no histórico de uso). Os outros processos herdam.
    static let dir = ProcessInfo.processInfo.environment["NIRI_CLIPBOARD"].map { URL(fileURLWithPath: $0) }
        ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support/niri-os/clipboard")
    private static let index = dir.appendingPathComponent("index.json")
    static func file(_ id: String, _ name: String) -> URL { dir.appendingPathComponent(id).appendingPathComponent(name) }

    /// Os dados de uma cópia, tipo → bytes. Mapeados do disco: um TIFF de 30 MB não vira 30 MB de quem lê.
    static func load(_ id: String) -> [String: Data]? {
        let names = (try? FileManager.default.contentsOfDirectory(atPath: dir.appendingPathComponent(id).path)) ?? []
        let data = Dictionary(uniqueKeysWithValues: names.filter { $0 != "thumbnail.png" }.compactMap { name in
            (try? Data(contentsOf: file(id, name), options: .mappedIfSafe)).map { (name, $0) }
        })
        return data.isEmpty ? nil : data
    }

    private var list = ClipboardList()
    private var seen = NSPasteboard.general.changeCount
    private var checking = false
    private var monitor: Any?
    private var reader: Process?
    private var panel: Process?
    private var input: Pipe?
    private let queue = DispatchQueue(label: "niri.clipboard", qos: .utility)

    private struct Saved: Codable {
        var boot: Double
        var list: ClipboardList
    }

    /// O que o processo de leitura responde.
    private struct Read: Codable {
        let digest: String
        let text: String?
    }

    /// Hora do boot do Mac: muda só quando ele reinicia (anda uns segundos com o ajuste do relógio).
    private static let bootTime: Double = {
        var tv = timeval(), size = MemoryLayout<timeval>.size
        sysctlbyname("kern.boottime", &tv, &size, nil, 0)
        return Double(tv.tv_sec)
    }()

    init() {
        let fm = FileManager.default
        try? fm.createDirectory(at: Self.dir, withIntermediateDirectories: true)
        let saved = (try? Data(contentsOf: Self.index)).flatMap { try? JSONDecoder().decode(Saved.self, from: $0) }
        list = saved?.list ?? ClipboardList()
        // Reiniciar o niri-os (versão nova) mantém tudo; reiniciar o Mac, só os fixados.
        if let saved, abs(saved.boot - Self.bootTime) > 60 { _ = list.dropRecent() }
        // Pasta sem cópia na lista: os recentes do boot anterior, ou queda no meio de uma leitura.
        let keep = Set(list.items.map(\.id))
        for f in (try? fm.contentsOfDirectory(at: Self.dir, includingPropertiesForKeys: nil)) ?? []
        where f != Self.index && !keep.contains(f.lastPathComponent) {
            try? fm.removeItem(at: f)
        }
        save()
        monitor = NSEvent.addGlobalMonitorForEvents(matching: [.keyDown, .leftMouseUp, .rightMouseUp]) { [weak self] e in
            let key = Int(e.keyCode)
            if e.type != .keyDown || e.modifierFlags.contains(.command) || key == kVK_Return || key == kVK_ANSI_KeypadEnter {
                self?.checkSoon()
            }
        }
    }

    /// Histórico desligado no painel. O que já foi copiado fica no disco, pra religar voltar igual.
    deinit {
        if let monitor { NSEvent.removeMonitor(monitor) }
        close()
    }

    // MARK: - Painel

    func toggle() { panel == nil ? open() : close() }

    private func open() {
        check()  // cópia feita sem tecla nem clique entra (chega logo depois, numa linha nova)
        let input = Pipe(), output = Pipe(), mouse = NSEvent.mouseLocation
        let p = Self.process(["--clipboard", "\(mouse.x)", "\(mouse.y)"], output: output)
        p.standardInput = input
        output.fileHandleForReading.readabilityHandler = { [weak self] h in
            let data = h.availableData
            if data.isEmpty { h.readabilityHandler = nil; return }
            let lines = String(decoding: data, as: UTF8.self).split(separator: "\n")
            DispatchQueue.main.async { lines.forEach { self?.command($0) } }
        }
        p.terminationHandler = { [weak self] p in
            // SIGTERM é o atalho fechando; o resto é queda.
            let crashed = p.terminationReason == .uncaughtSignal ? p.terminationStatus != SIGTERM : p.terminationStatus != 0
            if crashed { log("clipboard: o painel caiu (\(p.terminationReason == .uncaughtSignal ? "sinal" : "código") \(p.terminationStatus))") }
            DispatchQueue.main.async { if self?.panel === p { self?.panel = nil } }
        }
        do {
            try p.run()
        } catch {
            return log("clipboard: não consegui abrir o painel: \(error)")
        }
        panel = p
        self.input = input
        send()
    }

    func close() {
        panel?.terminate()
        panel = nil
    }

    private func send() {
        guard panel != nil, let handle = input?.fileHandleForWriting, let json = try? JSONEncoder().encode(list) else { return }
        // Na fila: com textos longos a lista passa dos 64 KB do pipe, e a escrita esperaria o painel começar a ler.
        // SIGPIPE ignorado (main): se o painel acabou de sair, a escrita só falha.
        queue.async { try? handle.write(contentsOf: json + Data("\n".utf8)) }
    }

    /// O painel aplica o mesmo pedido na cópia dele da lista: não precisa de resposta.
    private func command(_ line: Substring) {
        let word = line.split(separator: " ").map(String.init)
        guard word.count >= 2 else { return log("clipboard: pedido desconhecido do painel '\(line)'") }
        let id = word[1]
        switch word[0] {
        case "paste":
            // O painel já pôs a cópia no clipboard (o contador novo vem junto) e tirou a janela da tela: o teclado
            // voltou pro app da frente.
            if let count = word.last.flatMap(Int.init) { seen = count }
            list.touch(id, at: .now)
            Self.sendPaste()
        case "pin", "unpin":
            let r = list.setPinned(id, word[0] == "pin")
            delete(r.removed)
        case "delete":
            list.remove(id)
            delete([id])
        default: return log("clipboard: pedido desconhecido do painel '\(line)'")
        }
        save()
    }

    /// Cmd+V no nível de sessão: depois do tap dos atalhos (nível HID), que não vê. Os modificadores vão no evento,
    /// então o Option do Option+V ainda apertado não entra.
    private static func sendPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let e = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
            e?.flags = .maskCommand
            e?.post(tap: .cgSessionEventTap)
        }
    }

    // MARK: - Leitura

    /// A cópia chega ao clipboard logo depois da tecla ou do clique, às vezes dezenas de ms depois (app que escreve
    /// fora da main, `pbcopy` ainda rodando): confere aos 0,15 s e de novo aos 0,6 s.
    private func checkSoon() {
        guard !checking else { return }
        checking = true
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { [weak self] in self?.check() }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) { [weak self] in
            self?.check()
            self?.checking = false
        }
    }

    /// Uma leitura por vez; a que chegar no meio confere de novo quando ela acabar.
    private func check() {
        let count = NSPasteboard.general.changeCount
        guard count != seen, reader == nil else { return }
        seen = count
        let id = UUID().uuidString, app = NSWorkspace.shared.frontmostApplication?.localizedName, output = Pipe()
        let p = Self.process(["--clipboard-read", id, "\(count)"], output: output)
        p.terminationHandler = { [weak self] _ in
            // A resposta é uma linha curta (o texto vem cortado em `textLimit`): cabe no pipe, o processo não trava escrevendo.
            let read = try? JSONDecoder().decode(Read.self, from: output.fileHandleForReading.readDataToEndOfFile())
            DispatchQueue.main.async { [weak self] in
                guard let self else { return }
                reader = nil
                added(id, read, app: app)
                check()
            }
        }
        do {
            try p.run()
        } catch {
            return log("clipboard: não consegui ler a cópia: \(error)")
        }
        reader = p
        // App de origem travado entregando os dados: não segura as próximas cópias.
        DispatchQueue.main.asyncAfter(deadline: .now() + 5) { [weak self] in
            if self?.reader === p { p.terminate() }
        }
    }

    private func added(_ id: String, _ read: Read?, app: String?) {
        guard let read else { return delete([id]) }  // sigilosa, arquivo do Finder, grande demais, ou não deu pra ler
        if let old = list.item(digest: read.digest) {
            list.touch(old.id, at: .now)
            delete([id])
        } else {
            delete(list.add(.init(id: id, text: read.text, digest: read.digest, app: app, date: .now)))
        }
        save()
        send()
    }

    /// O processo da leitura: grava a cópia em `<dir>/<id>/`, um arquivo por formato, e responde o hash e o texto.
    /// Sai sem nada se o clipboard mudou de novo desde `count` (a próxima conferência pega a nova).
    static func readProcess(_ id: String, expecting count: Int) -> Never {
        let pb = NSPasteboard.general
        guard pb.changeCount == count, let types = pb.types, !types.contains(where: { secret.contains($0.rawValue) }),
              !types.contains(.fileURL)  // arquivo copiado no Finder: entraria só o nome
        else { exit(0) }
        var data: [String: Data] = [:]
        let text = pb.string(forType: .string).flatMap { $0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : $0 }
        if text != nil {
            for t in textTypes where types.contains(t) { data[t.rawValue] = pb.data(forType: t) }
        } else if let t = imageTypes.first(where: types.contains) {
            data[t.rawValue] = pb.data(forType: t)
        }
        guard let first = data.values.first, data.values.reduce(0, { $0 + $1.count }) <= maxBytes, pb.changeCount == count
        else { exit(0) }
        try? FileManager.default.createDirectory(at: dir.appendingPathComponent(id), withIntermediateDirectories: true)
        for (type, bytes) in data { try? bytes.write(to: file(id, type), options: .atomic) }
        let digest = SHA256.hash(data: text.map { Data($0.utf8) } ?? first).map { String(format: "%02x", $0) }.joined()
        let read = Read(digest: digest, text: text.map { String($0.prefix(ClipboardList.textLimit)) })
        try? FileHandle.standardOutput.write(contentsOf: JSONEncoder().encode(read))
        exit(0)
    }

    // MARK: - Disco

    private static func process(_ args: [String], output: Pipe) -> Process {
        let p = Process()
        p.executableURL = Bundle.main.executableURL
        p.arguments = args
        p.standardOutput = output
        return p
    }

    private func save() {
        guard let json = try? JSONEncoder().encode(Saved(boot: Self.bootTime, list: list)) else { return }
        queue.async { try? json.write(to: Self.index, options: .atomic) }
    }

    private func delete(_ ids: [String]) {
        guard !ids.isEmpty else { return }
        queue.async { for id in ids { try? FileManager.default.removeItem(at: Self.dir.appendingPathComponent(id)) } }
    }
}
